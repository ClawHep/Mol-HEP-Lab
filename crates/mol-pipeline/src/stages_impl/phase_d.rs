/// Execute the ExperimentDesign stage.
///
/// Reads hypotheses and synthesis; produces `exp_plan.yaml`.
/// This is a GATE stage — returns BlockedApproval when not auto-approved.
pub async fn execute_experiment_design(stage: Stage, ctx: &StageContext) -> StageResult {
    let stage_dir = ctx.stage_dir(stage);
    if let Err(e) = fs::create_dir_all(&stage_dir) {
        return StageResult::failure(stage, format!("create stage dir: {e}"));
    }

    let topic = ctx.config.topic.as_str();
    let _hypotheses = read_prior_artifact_pub(&ctx.run_dir, "hypotheses.md").unwrap_or_default();
    let _synthesis = read_prior_artifact_pub(&ctx.run_dir, "synthesis_report.md").unwrap_or_default();

    // ---- exp_plan.yaml -----------------------------------------------------
    let exp_plan_yaml = format!(
        r#"# Experiment Plan
# Generated by ExperimentDesign stage

topic: "{topic}"
generated_at: "{ts}"

# Primary hypothesis being tested
primary_hypothesis: "H1: Cross-Domain Transfer"

# Evaluation metric
metric:
  name: accuracy
  direction: max
  primary: true

# Baselines to compare against
baselines:
  - name: source_only
    description: Trained on source domain only, no adaptation
  - name: fine_tuning_upper_bound
    description: Fine-tuned on full target domain data
  - name: best_prior_method
    description: Best performing prior domain adaptation method

# Experimental conditions
conditions:
  - name: proposed_method
    description: Our proposed cross-domain transfer approach
    config:
      learning_rate: 1.0e-4
      batch_size: 32
      epochs: 50
      optimizer: adam

# Dataset splits
datasets:
  source:
    name: source_domain_dataset
    split: "80/10/10"
  target:
    - name: target_domain_1
    - name: target_domain_2
    - name: target_domain_3
    - name: target_domain_4
    - name: target_domain_5

# Ablation studies
ablations:
  - name: no_domain_adaptation
    remove_component: domain_adaptation_module
  - name: no_pretraining
    remove_component: self_supervised_pretraining
  - name: reduced_data
    data_fraction: 0.5

# Success criteria
success_criteria:
  primary: "At least 10% improvement over source_only baseline on 3+ target domains"
  secondary: "Statistical significance: p < 0.05"
  tertiary: "Inference time <= 2x baseline"

# Reproducibility settings
reproducibility:
  random_seeds: [42, 123, 456, 789, 1024]
  deterministic: true
  report_mean_std: true

# Resource requirements (estimated)
resources:
  gpu: "1x V100 or equivalent"
  memory_gb: 32
  disk_gb: 50
  estimated_hours: 24
"#,
        topic = topic,
        ts = utcnow_iso(),
    );

    if let Err(e) = fs::write(stage_dir.join("exp_plan.yaml"), &exp_plan_yaml) {
        return StageResult::failure(stage, format!("write exp_plan.yaml: {e}"));
    }

    if !ctx.auto_approve_gates {
        return StageResult {
            stage,
            status: StageStatus::BlockedApproval,
            artifacts: vec!["exp_plan.yaml".to_owned()],
            error: None,
            decision: "awaiting_approval".to_owned(),
            elapsed_secs: 0.0,
        };
    }

    StageResult {
        stage,
        status: StageStatus::Done,
        artifacts: vec!["exp_plan.yaml".to_owned()],
        error: None,
        decision: "proceed".to_owned(),
        elapsed_secs: 0.0,
    }
}

