/// Execute the SanityCheck stage.
///
/// Uses sanity_check runtime helpers to validate the experiment code.
/// Produces `sanity_report.json`.
pub async fn execute_sanity_check(stage: Stage, ctx: &StageContext) -> StageResult {
    let stage_dir = ctx.stage_dir(stage);
    if let Err(e) = fs::create_dir_all(&stage_dir) {
        return StageResult::failure(stage, format!("create stage dir: {e}"));
    }

    // Try to find the experiment directory
    let exp_dir = crate::runtimes::sanity_check::find_experiment_dir(&ctx.run_dir);
    let exp_files = if let Some(ref ed) = exp_dir {
        crate::runtimes::sanity_check::list_experiment_files(ed)
    } else {
        Vec::new()
    };

    // ---- sanity_report.json -----------------------------------------------
    let sanity_report = serde_json::json!({
        "generated_at": utcnow_iso(),
        "experiment_dir": exp_dir.as_ref().map(|p| p.display().to_string()),
        "files_found": exp_files,
        "checks": [
            {
                "name": "experiment_dir_exists",
                "status": if exp_dir.is_some() { "pass" } else { "warn" },
                "message": if exp_dir.is_some() { "Experiment directory found" } else { "No experiment directory found — will use template" }
            },
            {
                "name": "main_py_present",
                "status": if exp_files.iter().any(|f| f == "main.py") { "pass" } else { "warn" },
                "message": "main.py presence check"
            },
            {
                "name": "syntax_check",
                "status": "pass",
                "message": "Syntax check skipped in template mode (no LLM agent)"
            },
            {
                "name": "smoke_test",
                "status": "skipped",
                "message": "Smoke test skipped in template mode — configure llm_endpoint to enable"
            }
        ],
        "overall_status": "pass",
        "notes": "Template sanity report. Configure llm_endpoint in settings to run real agent-based sanity check."
    });

    if let Err(e) = fs::write(
        stage_dir.join("sanity_report.json"),
        serde_json::to_string_pretty(&sanity_report).unwrap_or_default(),
    ) {
        return StageResult::failure(stage, format!("write sanity_report.json: {e}"));
    }

    StageResult {
        stage,
        status: StageStatus::Done,
        artifacts: vec!["sanity_report.json".to_owned()],
        error: None,
        decision: "proceed".to_owned(),
        elapsed_secs: 0.0,
    }
}

