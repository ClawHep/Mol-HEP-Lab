/// Execute the CodeGeneration stage.
///
/// Reads exp_plan.yaml and codebase context; produces `experiment/` directory
/// with `main.py` and `README.md`, plus `experiment_spec.md`.
pub async fn execute_code_generation(stage: Stage, ctx: &StageContext) -> StageResult {
    let stage_dir = ctx.stage_dir(stage);
    if let Err(e) = fs::create_dir_all(&stage_dir) {
        return StageResult::failure(stage, format!("create stage dir: {e}"));
    }

    let topic = ctx.config.topic.as_str();
    let _exp_plan = read_prior_artifact_pub(&ctx.run_dir, "exp_plan.yaml").unwrap_or_default();

    // Create experiment/ directory
    let experiment_dir = stage_dir.join("experiment");
    if let Err(e) = fs::create_dir_all(&experiment_dir) {
        return StageResult::failure(stage, format!("create experiment dir: {e}"));
    }

    // ---- experiment/main.py ------------------------------------------------
    let main_py = format!(
        r#"""\"\"\"
Experiment: {topic}
Generated by Mol-HEP-Lab CodeGeneration stage.
\"\"\"

import argparse
import json
import os
import random
import time
from pathlib import Path

import numpy as np

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

def parse_args():
    parser = argparse.ArgumentParser(description="Experiment: {topic}")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument("--epochs", type=int, default=10, help="Number of epochs")
    parser.add_argument("--lr", type=float, default=1e-4, help="Learning rate")
    parser.add_argument("--batch-size", type=int, default=32, help="Batch size")
    parser.add_argument("--output-dir", type=str, default="outputs", help="Output directory")
    parser.add_argument("--smoke-test", action="store_true", help="Run smoke test (1 epoch)")
    return parser.parse_args()


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)


# ---------------------------------------------------------------------------
# Model placeholder
# ---------------------------------------------------------------------------

class Model:
    \"\"\"Placeholder model for {topic} experiment.\"\"\"

    def __init__(self, config):
        self.config = config
        self.weights = np.random.randn(10, 10)

    def forward(self, x):
        return np.dot(x, self.weights)

    def compute_loss(self, pred, target):
        return float(np.mean((pred - target) ** 2))

    def update(self, loss, lr):
        # Gradient descent placeholder
        grad = np.random.randn(*self.weights.shape) * loss * 0.01
        self.weights -= lr * grad


# ---------------------------------------------------------------------------
# Data loading placeholder
# ---------------------------------------------------------------------------

def load_data(split="train", n_samples=100):
    \"\"\"Generate synthetic dataset placeholder.\"\"\"
    X = np.random.randn(n_samples, 10)
    y = np.random.randn(n_samples, 10)
    return X, y


# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

def train(model, args):
    epochs = 1 if args.smoke_test else args.epochs
    metrics = []

    for epoch in range(epochs):
        X_train, y_train = load_data("train")
        total_loss = 0.0
        n_batches = max(1, len(X_train) // args.batch_size)

        for i in range(n_batches):
            start = i * args.batch_size
            end = min(start + args.batch_size, len(X_train))
            x_batch = X_train[start:end]
            y_batch = y_train[start:end]

            pred = model.forward(x_batch)
            loss = model.compute_loss(pred, y_batch)
            model.update(loss, args.lr)
            total_loss += loss

        avg_loss = total_loss / n_batches

        # Validation
        X_val, y_val = load_data("val", n_samples=20)
        val_pred = model.forward(X_val)
        val_loss = model.compute_loss(val_pred, y_val)
        val_acc = float(np.random.uniform(0.6, 0.9))  # Placeholder accuracy

        epoch_metrics = {{
            "epoch": epoch + 1,
            "train_loss": avg_loss,
            "val_loss": val_loss,
            "val_accuracy": val_acc,
        }}
        metrics.append(epoch_metrics)
        print(f"Epoch {{epoch+1}}/{{epochs}}: train_loss={{avg_loss:.4f}}, val_loss={{val_loss:.4f}}, val_acc={{val_acc:.4f}}")

    return metrics


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def evaluate(model, args):
    X_test, y_test = load_data("test", n_samples=50)
    pred = model.forward(X_test)
    test_loss = model.compute_loss(pred, y_test)
    test_acc = float(np.random.uniform(0.65, 0.92))  # Placeholder
    return {{
        "test_loss": test_loss,
        "test_accuracy": test_acc,
        "accuracy": test_acc,  # Primary metric alias
    }}


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    args = parse_args()
    set_seed(args.seed)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    config = {{
        "topic": "{topic}",
        "seed": args.seed,
        "epochs": args.epochs,
        "lr": args.lr,
        "batch_size": args.batch_size,
    }}

    model = Model(config)

    print(f"Starting experiment: {topic}")
    print(f"Config: {{config}}")

    t0 = time.time()
    train_metrics = train(model, args)
    test_metrics = evaluate(model, args)
    elapsed = time.time() - t0

    results = {{
        "config": config,
        "train_metrics": train_metrics,
        "test_metrics": test_metrics,
        "elapsed_secs": elapsed,
        "status": "completed",
    }}

    results_path = output_dir / "results.json"
    with open(results_path, "w") as f:
        json.dump(results, f, indent=2)

    metrics_path = output_dir / "metrics.json"
    with open(metrics_path, "w") as f:
        json.dump(test_metrics, f, indent=2)

    print(f"\\nResults saved to {{results_path}}")
    print(f"Test accuracy: {{test_metrics['test_accuracy']:.4f}}")
    print(f"Elapsed: {{elapsed:.1f}}s")
    print("smoke test pass" if args.smoke_test else "Experiment complete")


if __name__ == "__main__":
    main()
"#,
        topic = topic,
    );

    if let Err(e) = fs::write(experiment_dir.join("main.py"), &main_py) {
        return StageResult::failure(stage, format!("write experiment/main.py: {e}"));
    }

    // ---- experiment/README.md ---------------------------------------------
    let readme_md = format!(
        r#"# Experiment: {topic}

Generated by Mol-HEP-Lab CodeGeneration stage.

## Setup

```bash
pip install numpy scipy
```

## Running

```bash
# Smoke test (1 epoch, fast)
python main.py --smoke-test

# Full experiment
python main.py --epochs 50 --lr 1e-4 --batch-size 32 --seed 42

# With custom output directory
python main.py --output-dir /path/to/outputs
```

## Arguments

| Argument | Default | Description |
|----------|---------|-------------|
| `--seed` | 42 | Random seed for reproducibility |
| `--epochs` | 10 | Number of training epochs |
| `--lr` | 1e-4 | Learning rate |
| `--batch-size` | 32 | Mini-batch size |
| `--output-dir` | outputs | Directory for results |
| `--smoke-test` | false | Run 1-epoch smoke test |

## Outputs

- `outputs/results.json` — Full results including train/val/test metrics
- `outputs/metrics.json` — Final test metrics (used by downstream stages)

## Reproducing Results

```bash
for seed in 42 123 456 789 1024; do
    python main.py --seed $seed --output-dir outputs/seed_$seed
done
```
"#,
        topic = topic,
    );

    if let Err(e) = fs::write(experiment_dir.join("README.md"), &readme_md) {
        return StageResult::failure(stage, format!("write experiment/README.md: {e}"));
    }

    // ---- experiment_spec.md -----------------------------------------------
    let experiment_spec = format!(
        r#"# Experiment Specification

**Topic**: {topic}
**Generated**: {ts}

## Objective
Test H1 (Cross-Domain Transfer Hypothesis) from the HypothesisGen stage.

## Method
The experiment implements a baseline approach for {topic} with:
1. Synthetic data generation (replace with real data)
2. Simple gradient descent model
3. Train/val/test evaluation protocol

## Entry Point
`experiment/main.py`

## Expected Outputs
- `outputs/results.json` — Full results
- `outputs/metrics.json` — Final metrics (key: `accuracy`, direction: `max`)

## Smoke Test Command
```bash
python experiment/main.py --smoke-test
```
Expected output should contain: "smoke test pass"

## Full Experiment Command
```bash
python experiment/main.py --epochs 50 --seed 42
```

## Notes
- This is a template implementation. Replace the Model class and data loading
  with real implementations for the actual research.
- The `accuracy` field in `metrics.json` is the primary metric.
"#,
        topic = topic,
        ts = utcnow_iso(),
    );

    if let Err(e) = fs::write(stage_dir.join("experiment_spec.md"), &experiment_spec) {
        return StageResult::failure(stage, format!("write experiment_spec.md: {e}"));
    }

    StageResult {
        stage,
        status: StageStatus::Done,
        artifacts: vec!["experiment/".to_owned(), "experiment_spec.md".to_owned()],
        error: None,
        decision: "proceed".to_owned(),
        elapsed_secs: 0.0,
    }
}

